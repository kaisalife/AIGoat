# AIGoat 一键打包：收集 codex.exe → 前端 + 壳构建 → NSIS 安装包。
# 用法：powershell -ExecutionPolicy Bypass -File tools\package.ps1
# 产物：src-tauri\target\release\bundle\nsis\AIGoat_0.1.0_x64-setup.exe
#
# codex.exe 不在这里编译：迁入源码的 release 产物已存在，直接收集
# （tools 见 docs/打包部署/打包部署方案.md 5.1 节）。
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot

# ① 收集 codex.exe：迁入源码的现成 release 产物 → src-tauri\bin\（不编译）。
$codexSrc = Join-Path $root "codex-rs\codex-rs\target\release\codex.exe"
if (-not (Test-Path $codexSrc)) { $codexSrc = "D:\Codex\Codex-cli-rs\bin\codex.exe" }  # PATH 同源产物备用位置
if (-not (Test-Path $codexSrc)) { throw "找不到 codex.exe 产物（迁入源码 target 与 D:\Codex\Codex-cli-rs\bin 均不存在）" }
$staging = Join-Path $root "src-tauri\bin"
New-Item -ItemType Directory -Force -Path $staging | Out-Null
Copy-Item $codexSrc (Join-Path $staging "codex.exe") -Force
Write-Host "[package] codex.exe ← $codexSrc" -ForegroundColor Cyan

# ①b 生成 NSIS 安装钩子：bundle.resources 对大文件会产出 0 字节实体（实测两次），
# 改用 makensis 原生 File 指令在安装时落盘。钩子每次打包重新生成，注入绝对路径。
$hook = @"
; Auto-generated by tools\package.ps1 (staging path varies per build machine). Do not edit.
!macro NSIS_HOOK_POSTINSTALL
  CreateDirectory "`$INSTDIR\bin"
  File /oname=`$INSTDIR\bin\codex.exe "$(Join-Path $staging 'codex.exe')"
!macroend
; Uninstaller only knows files from its own manifest: without this hook the
; hook-installed codex.exe (300+ MB) stays behind after uninstall. cache\ is
; user data and is intentionally kept.
!macro NSIS_HOOK_POSTUNINSTALL
  Delete "`$INSTDIR\bin\codex.exe"
  RMDir "`$INSTDIR\bin"
!macroend
"@
Set-Content -Path (Join-Path $root "src-tauri\installer-hooks.nsh") -Value $hook -Encoding ASCII
Write-Host "[package] installer-hooks.nsh 已生成" -ForegroundColor Cyan

# ② 构建 + 生成 NSIS 工程（beforeBuildCommand 自动 npm build 前端，随后嵌入 + bundle）。
Push-Location (Join-Path $root "src-tauri")
npx --no-install @tauri-apps/cli build
$code = $LASTEXITCODE
Pop-Location
if ($code -ne 0) { throw "tauri build 失败" }

# ③ NSIS 手动重编译：实测 CLI 产物在安装时把钩子 File 指令的数据解成 0 字节文件
#   （同一份 installer.nsi 手动 makensis 则完整），故用 CLI 生成的工程自行编译，
#   覆盖 bundle 目录里的最终安装包。
$nsisDir  = Join-Path $root "src-tauri\target\release\nsis\x64"
$makensis = Join-Path $env:LOCALAPPDATA "tauri\NSIS\makensis.exe"
if (-not (Test-Path $makensis)) { throw "找不到 makensis（$makensis），先跑一次 tauri build 让其下载" }
Push-Location $nsisDir
& $makensis installer.nsi | Select-String -Pattern "Output:" | ForEach-Object { Write-Host "[package] $_" -ForegroundColor DarkGray }
$code = $LASTEXITCODE
Pop-Location
if ($code -ne 0) { throw "makensis 编译失败" }
# setup 文件名随 tauri.conf.json 的 version 走，不写死。
$conf = Get-Content (Join-Path $root "src-tauri\tauri.conf.json") -Raw | ConvertFrom-Json
$setup = Join-Path $root "src-tauri\target\release\bundle\nsis\$($conf.productName)_$($conf.version)_x64-setup.exe"
Copy-Item (Join-Path $nsisDir "nsis-output.exe") $setup -Force

# ④ 自检：安装包存在且体积合理（含压缩后的 codex.exe，应远大于 aigoat.exe 本身）。
$setupItem = Get-Item $setup
if ($setupItem.Length -lt 60MB) { throw "安装包仅 $([Math]::Round($setupItem.Length / 1MB)) MB，codex.exe 数据疑似未打进包" }
if (-not (Test-Path (Join-Path $staging "codex.exe"))) { throw "staging 中缺少 codex.exe" }
Write-Host "[package] 完成: $($setupItem.FullName) ($([Math]::Round($setupItem.Length / 1MB)) MB)" -ForegroundColor Green
